import { NextResponse } from "next/server";
import { getSessionUser } from "@/lib/auth";
import { prisma } from "@/lib/db";
import { uploadToShelby } from "@/lib/shelby-server";
import { getShelbyPublicUrl } from "@/lib/shelby";

export async function GET(
  _request: Request,
  { params }: { params: Promise<{ slug: string }> }
) {
  const user = await getSessionUser();
  if (!user) return NextResponse.json({ error: "Unauthorized" }, { status: 401 });

  const { slug } = await params;
  const cert = await prisma.certificate.findFirst({
    where: { verificationSlug: slug, buyerId: user.id },
    include: {
      buyer: { select: { displayName: true, username: true } },
      seller: { select: { displayName: true, username: true } },
      asset: true,
      product: true,
    },
  });

  if (!cert) return NextResponse.json({ error: "Not found" }, { status: 404 });

  // Note: Certificate model does not persist pdfBlobId (unlike invoices). Always (re)generate for now.
  const html = `<!DOCTYPE html>
<html><head><meta charset="utf-8"><title>Certificate ${cert.certificateId}</title>
<style>
  body { font-family: system-ui, Georgia, serif; color: #313131; padding: 40px; max-width: 720px; margin: 0 auto; background: #f5f5f5; }
  .card { background: #ebebeb; padding: 40px; border-radius: 8px; border: 2px solid #dc5429; }
  h1 { color: #dc5429; margin: 0; font-size: 28px; }
  .meta { color: #5a5a5a; font-size: 13px; }
  .section { margin-top: 24px; }
  .row { display: flex; justify-content: space-between; margin: 8px 0; }
</style></head><body>
<div class="card">
  <h1>Certificate of Ownership</h1>
  <p class="meta">Forge • Verified on ShelbyNet</p>

  <div class="section">
    <div class="row"><strong>Certificate ID</strong><span class="font-mono">${cert.certificateId}</span></div>
    <div class="row"><strong>Item</strong><span>${cert.title}</span></div>
    <div class="row"><strong>Buyer</strong><span>${cert.buyer.displayName || cert.buyer.username}</span></div>
    <div class="row"><strong>Creator</strong><span>${cert.seller.displayName || cert.seller.username}</span></div>
    <div class="row"><strong>Amount</strong><span>${cert.txHash ? "See tx" : ""}</span></div>
    <div class="row"><strong>Purchased</strong><span>${cert.issuedAt.toLocaleDateString()}</span></div>
    <div class="row"><strong>Tx</strong><span class="font-mono text-xs break-all">${cert.txHash}</span></div>
  </div>

  <p style="margin-top:32px;font-size:12px;color:#5a5a5a">This certificate proves ownership. Present for disputes or licensing.</p>
  <p class="meta" style="margin-top:16px">Generated by Forge</p>
</div>
</body></html>`;

  // Generate on the fly (no pdfBlobId column on Certificate yet)
  return new NextResponse(html, {
    headers: { "Content-Type": "text/html", "Content-Disposition": `attachment; filename="certificate-${cert.certificateId}.html"` },
  });
}
