const MAP: Record<Locale, Dict> = { en, ko, zh, fr };

export function t(
  locale: Locale,
  key: string,
  vars?: Record<string, string | number>
): string {
  const str = MAP[locale][key] ?? MAP.en[key] ?? key;
  if (!vars) return str;
  return Object.entries(vars).reduce(
    (s, [k, v]) => s.replace(`{${k}}`, String(v)),
    str
  );
}
